#!/usr/bin/env python3
"""Build the dependency-free GitHub Pages site for an owner/repository."""
import argparse
import html
import json
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]


def build(repository: str, output: Path) -> None:
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repository):
        raise ValueError("repository must be owner/name")
    output = output.resolve()
    # Never overwrite source files, even when invoked with an incorrect output.
    if (output == ROOT or output in (ROOT / "website").parents
            or output == ROOT / "website" or ROOT / "website" in output.parents):
        raise ValueError("output must be a separate generated directory")
    if output.exists() and any(output.iterdir()):
        marker = output / ".opentv-generated"
        if not marker.is_file():
            raise ValueError("nonempty output directory was not generated by this tool")
    output.mkdir(parents=True, exist_ok=True)
    release = json.loads((ROOT / "website/release.json").read_text())
    repo_url = f"https://github.com/{repository}"
    base = f"{repo_url}/releases/download/{release['tag']}"
    values = {
        "REPO_URL": repo_url,
        "APK_URL": f"{base}/{release['apk']}",
        "RELEASE_URL": f"{repo_url}/releases/tag/{release['tag']}",
        "SOURCE_URL": f"{base}/{release['source']}",
        "CHECKSUM_URL": f"{base}/{release['checksum_file']}",
        **{key.upper(): str(value) for key, value in release.items()},
    }
    page = (ROOT / "website/index.html").read_text()
    for key, value in values.items():
        page = page.replace("{{" + key + "}}", html.escape(value, quote=True))
    if re.search(r"\{\{[^}]+\}\}", page):
        raise ValueError("unresolved website placeholder")
    (output / "index.html").write_text(page)
    shutil.copyfile(ROOT / "website/styles.css", output / "styles.css")
    shutil.copytree(ROOT / "website/assets", output / "assets", dirs_exist_ok=True)
    (output / ".nojekyll").touch()
    (output / ".opentv-generated").touch()
    print(f"Site ready: {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", default="levhakobyan/OpenTV-Cast")
    parser.add_argument("--output", type=Path, default=ROOT / "work/site-preview")
    args = parser.parse_args()
    build(args.repository, args.output)
